/**
 * PolyTrack car image.
 *
 * Prefers the game's own native render. `scripts/gen-car-pngs.mjs` drives the
 * real PolyTrack client headlessly and saves the 200x200 thumbnails its internal
 * `carThumbnail(carStyle)` helper produces, keyed by car style, into
 * `public/cars/<style>.png`. Those are static files, so this costs one image
 * request and no client-side rendering.
 *
 * Car styles we have not generated yet fall back to a schematic SVG drawn from
 * the decoded style, so the UI never shows a broken image.
 */
import { useEffect, useState } from 'react';
import { decodeCarStyle } from '@/lib/polytrack';
import { NATIVE_CAR_STYLES } from '@/lib/nativeCarStyles';

/**
 * Styles with a native PNG in `public/cars/`. Generated by
 * `scripts/gen-car-pngs.mjs`; a miss falls back to the SVG below rather than
 * requesting a file that does not exist.
 */
const NATIVE_STYLES = new Set<string>(NATIVE_CAR_STYLES);

/** Static URL for a style's native render, or null when we have not generated it. */
export function carImageUrl(carStyle?: string | null): string | null {
  if (!carStyle) return null;
  return NATIVE_STYLES.has(carStyle) ? `/cars/${encodeURIComponent(carStyle)}.png` : null;
}

/** Schematic fallback drawn from the decoded car style. */
function CarSvg({ carStyle, size, className }: { carStyle?: string | null; size: number; className?: string }) {
  const hex = decodeCarStyle(carStyle ?? '');
  const body = hex ? `#${hex.slice(0, 6)}` : '#8b7cf0';
  const accent = hex ? `#${hex.slice(6, 12)}` : '#f4f4ff';
  const pods = hex ? `#${hex.slice(12, 18)}` : '#2a2a3a';
  const dark = '#14141e';

  return (
    <svg
      width={size}
      height={size * 1.6}
      viewBox="0 0 40 64"
      className={className}
      aria-label="Player car"
      role="img"
    >
      <rect x="1" y="10" width="8" height="13" rx="2" fill={dark} />
      <rect x="31" y="10" width="8" height="13" rx="2" fill={dark} />
      <rect x="1" y="38" width="8" height="14" rx="2" fill={dark} />
      <rect x="31" y="38" width="8" height="14" rx="2" fill={dark} />
      <path d="M6 4h28l-3 5H9z" fill={pods} />
      <path
        d="M20 2 L26 10 L27 26 L30 34 L30 54 L10 54 L10 34 L13 26 L14 10 Z"
        fill={body}
        stroke={dark}
        strokeWidth="1.2"
      />
      <path d="M8 30 L13 28 L13 48 L8 46 Z" fill={pods} />
      <path d="M32 30 L27 28 L27 48 L32 46 Z" fill={pods} />
      <path d="M19 4 L21 10 L21 52 L17 52 L17 10 Z" fill={accent} opacity="0.85" />
      <path d="M15 30 h10 l-1.5 9 h-7 z" fill={dark} />
      <rect x="8" y="52" width="24" height="5" fill={pods} stroke={dark} strokeWidth="1" />
      <rect x="16" y="2.5" width="8" height="2.5" fill="#fff8d6" />
    </svg>
  );
}

export function CarPic({
  carStyle,
  size = 28,
  className,
}: {
  carStyle?: string | null;
  size?: number;
  className?: string;
}) {
  const url = carImageUrl(carStyle);
  const [failed, setFailed] = useState(false);

  // A style change should retry the native image rather than stay on the fallback.
  useEffect(() => setFailed(false), [url]);

  if (!url || failed) return <CarSvg carStyle={carStyle} size={size} className={className} />;

  return (
    <img
      src={url}
      width={size}
      height={size}
      loading="lazy"
      decoding="async"
      className={className}
      alt="Player car"
      onError={() => setFailed(true)}
    />
  );
}
